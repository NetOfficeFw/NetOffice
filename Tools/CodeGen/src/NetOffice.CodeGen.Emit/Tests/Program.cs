        private static void Main()
        {
            var root = Path.Combine(Path.GetTempPath(), "netoffice-codegen-tests-" + Guid.NewGuid().ToString("N"));
            try
            {
                var model = CompleteFixture();
                var first = new CSharpEmitter().Emit(model);
                var second = new CSharpEmitter().Emit(model);
                var permuted = CompleteFixture();
                permuted.Usings = permuted.Usings.Reverse().ToArray();
                permuted.Types = permuted.Types.Reverse().ToArray();
                foreach (var type in permuted.Types) type.Members = type.Members.Reverse().ToArray();
                var reordered = new CSharpEmitter().Emit(permuted);

                Assert(first.Bytes.SequenceEqual(second.Bytes), "identical IR must produce identical bytes");
                Assert(first.Bytes.SequenceEqual(reordered.Bytes), "canonical IR ordering must not depend on input collection order");
                Assert(first.Bytes[0] == 0xef && first.Bytes[1] == 0xbb && first.Bytes[2] == 0xbf, "source must have UTF-8 BOM");
                AssertReloadSafety(first);
                Assert(first.Text.Contains("ownership: D9") && !first.Text.Contains("<auto-generated"), "D9 marker must be stable and non-auto-generated");
                Assert(first.Text.Contains("public class Database : COMObject"), "Database must be emitted as a concrete wrapper class");
                Assert(first.Text.Contains("public Database(Core factory, ICOMObject parentObject, object comProxy) : base(factory, parentObject, comProxy)"), "standard wrapper constructors must be emitted");
                Assert(first.Text.Contains("public static Type LateBindingApiWrapperType"), "LateBindingApiWrapperType must match the wrapper runtime contract");
                Assert(first.Text.Contains("[EditorBrowsable(EditorBrowsableState.Advanced), Browsable(false), Category(\"NetOffice\"), CoreOverridden]"), "InstanceType must emit the baseline runtime attributes");
                Assert(first.Text.Contains("NetRuntimeSystem.Type comProxyType"), "proxy type constructor parameters must use the runtime alias");
                Assert(first.Text.Contains("[Obsolete(\"runtime contract\")]") && first.Text.Contains("/// <summary>Exact runtime docs.</summary>"), "runtime member contract overlays must preserve exact attributes and raw documentation");
                Assert(first.Text.Contains("Factory.ExecuteKnownReferenceMethodGet<Database>"), "known wrapper returns must use Factory");
                Assert(first.Text.Contains("Invoker.PropertyGet(this, \"DataSource\", paramsArray)"), "untyped reference returns must support the Invoker operation");
                Assert(first.Text.Contains("Factory.ExecuteEnumPropertySet(this, \"Mode\", value)"), "enum setters must use the enum Factory operation");
                Assert(first.Text.Contains("public Command() : base(\"Fixture.Command\")") && !first.Text.Contains("public Command(Core factory, ICOMObject parentObject, COMProxyShare proxyShare)"), "co-class runtime profile must emit its ProgID constructors without wrapper-only proxy-share construction");
                Assert(first.Text.Contains("public void CreateEventBridge()") && first.Text.Contains("public int RaiseCustomEvent(string eventName, ref object[] paramsArray)") && first.Text.Contains("public void DisposeEventBridge()"), "event-binding co-classes must implement the complete IEventBinding runtime");
                Assert(first.Text.Contains("public class ProjectInfo : IFactoryInfo") && first.Text.Contains("public bool Contains(Type type)") && first.Text.Contains("\"OfficeApi.dll\""), "ProjectInfo utility plan must emit the complete IFactoryInfo implementation");
                Assert(first.Text.Contains("return get_Collect(index);"), "local-forward invocation must emit a direct managed member call");
                Assert(first.Text.Contains("public void set_Option(DbKind value)"), "method members with empty producer return types must canonicalize to void");
                Assert(first.Text.Contains("private event ChangedHandler _CommandChangedEvent;") && first.Text.Contains("_CommandChangedEvent += value;") && first.Text.Contains("_CommandChangedEvent -= value;"), "custom event metadata must emit a backing event and bridge-aware accessors");
                Assert(first.Text.Contains("[Obsolete(\"exact constructor\")]"), "constructor contracts must replace default runtime constructor facets");
                Assert(first.Text.Contains("new object[]{ name }"), "explicit compact object-array style must preserve canonical Factory call shape");
                Assert(first.Text.Contains("static class DbConstants") && !first.Text.Contains("private static class DbConstants"), "top-level private accessibility must be represented by an omitted modifier");
                Assert(first.Text.Contains("Table = 1,\r\n") && first.Text.Contains("Query = 2\r\n") && !first.Text.Contains("Query = 2,"), "enum member order must be preserved and the final value must omit its comma");
                Assert(first.Text.Contains("public Database Open()") && first.Text.Contains("public Database Open(string name = \"default\")"), "method overloads must retain distinct invocation bodies");
                Assert(first.Text.Contains("object[] paramsArray = Invoker.ValidateParamsArray((object)state);"), "Invoker calls must validate exact argument expressions");
                Assert(first.Text.Contains("Invoker.ReleaseParamsArray(paramsArray)"), "requested argument release must be emitted");
                Assert(first.Text.Contains("ParameterModifier[] modifiers = Invoker.CreateParamModifiers(true);") && first.Text.Contains("Invoker.MethodReturn(this, \"ConvertState\", paramsArray, modifiers)"), "by-ref Invoker calls must emit parameter modifiers");
                Assert(first.Text.Contains("state = null;") && first.Text.Contains("ValidateParamsArray((object)state)"), "by-ref initialization must target the writable expression independently of the invocation expression");
                Assert(first.Text.Contains("Factory.ExecuteReferencePropertySet(this, \"Owner\", value)"), "putref setters must use reference property invocation");
                Assert(first.Text.Contains("Factory.ExecutePropertySet(this, \"QueryTimeout\", value)"), "value property setters must use Factory");
                Assert(first.Text.Contains("Factory.ExecuteValuePropertySet(this, \"ValueTimeout\", value)"), "typed value-property setter must select the specialized runtime call");
                Assert(first.Text.Contains("Factory.ExecutePropertySet(this, \"Item\", value, index)"), "marked property values must be selected without disturbing index argument order");
                Assert(first.Text.Contains("ICOMObject newObject = Factory.CreateObjectFromComProxy(this, returnItem);") && first.Text.Contains("return newObject;"), "untyped references must support independent local types and no-cast return form");
                Assert(first.Text.Contains("Database knownItem = Factory.CreateKnownObjectFromComProxy(this, returnItem, Database.LateBindingApiWrapperType) as Database;"), "known references must support non-generic factory and named local form");
                Assert(first.Text.Contains("object returnItem = (object)Invoker.MethodReturn(this, \"RawValue\""), "raw Invoker returns must support explicit object call casts");
                Assert(first.Text.Contains("return Invoker.PropertyGet(this, \"DirectContent\");"), "zero-argument Invoker gets must support direct return form");
                Assert(first.Text.Contains("Invoker.Method(this, \"Execute\", paramsArray);;"), "void Invoker calls must preserve an explicit double terminator");
                Assert(first.Text.Contains("public Database this[int index]"), "collection indexers must be emitted");
                Assert(first.Text.Contains("System.Collections.IEnumerable.GetEnumerator"), "explicit collection enumerators must be emitted");
                Assert(first.Text.Contains("using System.Runtime.CompilerServices;") && first.Text.Contains("using System.Runtime.InteropServices;"), "COM attributes must add their required framework usings");
                Assert(first.Text.Contains("public class DatabaseEvents_SinkHelper : SinkHelper, DatabaseEvents"), "COM event interfaces must synthesize sink helpers");
                Assert(first.Text.Contains("public void BeforeChange(") && first.Text.Contains("ref string name") && first.Text.Contains("out int count") && !first.Text.Contains("ref string name =") && !first.Text.Contains("out int count ="), "ref/out defaults must be removed while method modifiers are retained");
                var suppressedValidation = first.Text.IndexOf("if (!Validate(\"Suppressed\"))", StringComparison.Ordinal);
                Assert(first.Text.IndexOf("public void SinkOnly(", StringComparison.Ordinal) >= 0 && first.Text.IndexOf("public void SinkOnly(", StringComparison.Ordinal) == first.Text.LastIndexOf("public void SinkOnly(", StringComparison.Ordinal), "sink-only event members must be emitted once on the synthesized sink and omitted from the COM interface");
                var suppressedDispatch = first.Text.IndexOf("object[] paramsArray", suppressedValidation, StringComparison.Ordinal);
                Assert(suppressedValidation >= 0 && suppressedDispatch > suppressedValidation && first.Text.Substring(suppressedValidation, suppressedDispatch - suppressedValidation).IndexOf("ReleaseParamsArray", StringComparison.Ordinal) < 0, "suppressed sink validation release must emit no release call");
                Assert(!first.Text.Contains("[MarshalAs(UnmanagedType.BStr)] string query"), "concrete wrappers must not inherit native-interface parameter metadata");
                Assert(first.Text.Contains("[MarshalAs(UnmanagedType.BStr)] ref string name"), "event interfaces and synthesized sinks must retain contract-owned parameter metadata");
                Assert(first.Text.Contains("int convertedCount = ToInt32(count + 0);") && first.Text.Contains("count = ToInt32(paramsArray[1]);"), "sink helpers must preserve exact conversion source/local names and write back the original parameter");
                Assert(first.Text.Contains("Invoker.ReleaseParamsArray(); return;"), "sink validation may preserve a legacy same-line release and return");
                Assert(first.Text.Contains("/// <remarks>\r\n") && first.Text.IndexOf("/// <remarks>", StringComparison.Ordinal) < first.Text.IndexOf("/// <summary>Raw contract docs.</summary>", StringComparison.Ordinal), "raw XML documentation order must be preserved");
                Assert(first.Text.Contains("new object[] { value0, value1, value2, value3, value4, value5, value6, value7, value8 }"), "large Factory calls must use the runtime array overload");
                Assert(first.Text.Contains("Factory.ExecuteBoolMethodGet(this, \"IsOpen\")"), "Factory scalar method names must match the NetOffice runtime");
                Assert(first.Text.Contains("private static ICOMObject _instance;") && first.Text.Contains("internal static Core Factory") && first.Text.Contains("internal static Invoker Invoker"), "modules must emit static COM runtime infrastructure");
                Assert(first.Text.Contains("Factory.ExecuteStringPropertyGet(Instance, \"ExplicitVersion\")"), "module invocations must preserve explicit non-default targets");
                Assert(first.Text.Contains("Factory.ExecuteStringPropertyGet(_instance, \"Version\")") && !first.Text.Contains("Factory.ExecuteStringPropertyGet(this, \"Version\")"), "module invocations must preserve the selected API while targeting the module instance");
                Assert(first.Text.Contains("if(null != _instance)\r\n                    return _instance.Invoker;\r\n                else\r\n                    return Invoker.Default;"), "module runtime getters must preserve the baseline explicit else shape");
                Assert(first.Text.Contains("public static class Global") && first.Text.Contains("static class DbConstants"), "modules and constant containers must be emitted as static classes");
                Assert(first.Text.Contains("enum DbKind") && first.Text.Contains("public delegate void ChangedHandler"), "enums and delegates must be emitted");
                Assert(first.Text.Contains("EventBinding.RaiseCustomEvent"), "sink helpers must raise typed events");
                Assert(first.Text.Contains("/// <summary>") && first.Text.Contains("/// <param name=\"query\">"), "structured XML documentation must be emitted");
                Assert(first.Text.Contains("[Serializable]"), "attributes must be emitted");
                Assert(first.Text.EndsWith("\r\n", StringComparison.Ordinal) && first.Text.IndexOf('\n') == first.Text.IndexOf("\r\n", StringComparison.Ordinal) + 1, "source must use CRLF");

                AssertCompiles(first.Text);
                AssertInvalidSyntaxRejected(model.RelativePath);
                AssertStorageSafety(root, first, model);
                Console.WriteLine("Emission/storage tests passed.");
            }
            finally
            {
                if (Directory.Exists(root)) Directory.Delete(root, true);
            }
        }

