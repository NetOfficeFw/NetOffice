using System;
using System.IO;
using System.Linq;
using NetOffice.CodeGen.Emit;
using NetOffice.CodeGen.Storage;

namespace NetOffice.CodeGen.Emit.Tests
{
    internal static class Program
    {
        private static void Main()
        {
            var root = Path.Combine(Path.GetTempPath(), "netoffice-codegen-tests-" + Guid.NewGuid().ToString("N"));
            var model = new WrapperFile
            {
                RelativePath = "Excel/Generated/Stable.cs",
                Namespace = "Fixture",
                Usings = new[] { "System" },
                Types = new[] { new WrapperType { Name = "Stable", Members = new[] { new WrapperMember { Name = "Value", Kind = "property", Type = "string", Documentation = new WrapperDocumentation { Summary = "A & B" } } } } }
            };
            var first = new CSharpEmitter().Emit(model);
            var second = new CSharpEmitter().Emit(model);
            Assert(first.Bytes.SequenceEqual(second.Bytes), "identical IR must produce identical bytes");
            Assert(first.Bytes[0] == 0xef && first.Bytes[1] == 0xbb && first.Bytes[2] == 0xbf, "source must have UTF-8 BOM");
            Assert(first.Text.Contains("ownership: D9") && !first.Text.Contains("<auto-generated"), "D9 marker must be stable and non-auto-generated");
            Assert(first.Text.EndsWith("\r\n", StringComparison.Ordinal) && first.Text.IndexOf('\n') == first.Text.IndexOf("\r\n", StringComparison.Ordinal) + 1, "source must use CRLF");
            var initial = GenerationPlanBuilder.Build(root, new[] { first }, null, new PlanOptions { GeneratorVersion = "test" });
            initial.Apply();
            var manifestPath = Path.Combine(root, ".codegen", "ownership.json");
            var manifest = OwnershipManifest.Parse(File.ReadAllBytes(manifestPath));
            var stable = GenerationPlanBuilder.Build(root, new[] { first }, manifest, new PlanOptions { GeneratorVersion = "test" });
            Assert(!stable.HasChanges, "unchanged generation must be a no-op");
            var managedPath = Path.Combine(root, "Excel", "Generated", "Stable.cs");
            File.AppendAllText(managedPath, "drift");
            try { GenerationPlanBuilder.Build(root, new[] { first }, manifest); throw new Exception("hash drift was accepted"); }
            catch (HashMismatchException) { }
            File.WriteAllBytes(managedPath, first.Bytes);
            var changed = new CSharpEmitter().Emit(new WrapperFile { RelativePath = model.RelativePath, Namespace = model.Namespace, Types = new[] { new WrapperType { Name = "Stable", Members = new[] { new WrapperMember { Name = "Value", Kind = "property", Type = "int" } } } } });
            var rollback = GenerationPlanBuilder.Build(root, new[] { changed }, manifest, new PlanOptions { BeforeOperation = (index, operation) => { if (index == 1) throw new InvalidOperationException("fault"); } });
            try { rollback.Apply(); throw new Exception("fault injection did not fail"); }
            catch (InvalidOperationException error) { Assert(error.Message == "fault", "unexpected rollback fault"); }
            Assert(File.ReadAllBytes(managedPath).SequenceEqual(first.Bytes), "rollback must restore managed bytes");
            Assert(File.ReadAllBytes(manifestPath).SequenceEqual(manifest.ToUtf8()), "rollback must restore manifest bytes");
            Console.WriteLine("Emission/storage tests passed.");
        }

        private static void Assert(bool condition, string message) { if (!condition) throw new Exception(message); }
    }
}
