using System;
using System.Collections.Generic;
using System.Linq;
using System.Security;
using System.Security.Cryptography;
using System.Text;

namespace NetOffice.CodeGen.Emit
{
    public static class OwnershipMarker
    {
        public const string D9 = "// NetOffice.CodeGen ownership: D9";
    }

    public sealed class EmitterOptions
    {
        public string ProductName { get; set; }
        public string GeneratedBy { get; set; }
        public bool IncludeOwnershipMarker { get; set; } = true;
        public ISourceValidator Validator { get; set; } = new BasicSourceValidator();
    }

    public sealed class EmittedFile
    {
        public string RelativePath { get; internal set; }
        public byte[] Bytes { get; internal set; }
        public string Sha256 { get; internal set; }
        public long Length { get { return Bytes == null ? 0 : Bytes.LongLength; } }
        public string Text { get { return Bytes == null ? string.Empty : new UTF8Encoding(true).GetString(Bytes, 3, Bytes.Length - 3); } }
    }

    public interface ISourceValidator
    {
        void Validate(string relativePath, string source);
    }

    /// <summary>Dependency-free validation seam used when Roslyn is not available.</summary>
    public sealed class BasicSourceValidator : ISourceValidator
    {
        public void Validate(string relativePath, string source)
        {
            if (string.IsNullOrWhiteSpace(relativePath)) throw new InvalidOperationException("An emitted source path is required.");
            if (source == null || !source.EndsWith("\r\n", StringComparison.Ordinal)) throw new InvalidOperationException("Emitted source must end in CRLF.");
            if (source.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0) throw new InvalidOperationException("The D9 marker must not be an auto-generated marker.");
            var braces = 0;
            var inString = false;
            var inChar = false;
            var escaped = false;
            foreach (var ch in source)
            {
                if (escaped) { escaped = false; continue; }
                if ((inString || inChar) && ch == '\\') { escaped = true; continue; }
                if (!inChar && ch == '"') { inString = !inString; continue; }
                if (!inString && ch == '\'') { inChar = !inChar; continue; }
                if (inString || inChar) continue;
                if (ch == '{') braces++;
                else if (ch == '}' && --braces < 0) throw new InvalidOperationException("Unbalanced braces in " + relativePath + ".");
            }
            if (braces != 0 || inString || inChar) throw new InvalidOperationException("Unbalanced C# delimiters in " + relativePath + ".");
        }
    }

    public sealed class CSharpEmitter
    {
        private static readonly Encoding Utf8Bom = new UTF8Encoding(true);
        private readonly EmitterOptions options;

        public CSharpEmitter(EmitterOptions options = null) { this.options = options ?? new EmitterOptions(); }

        public EmittedFile Emit(WrapperFile input)
        {
            if (input == null) throw new ArgumentNullException(nameof(input));
            var file = input.Canonicalize();
            var source = Render(file);
            if (options.Validator != null) options.Validator.Validate(file.RelativePath, source);
            var encoded = Utf8Bom.GetBytes(source);
            var preamble = Utf8Bom.GetPreamble();
            var bytes = new byte[preamble.Length + encoded.Length];
            Buffer.BlockCopy(preamble, 0, bytes, 0, preamble.Length);
            Buffer.BlockCopy(encoded, 0, bytes, preamble.Length, encoded.Length);
            return new EmittedFile { RelativePath = file.RelativePath, Bytes = bytes, Sha256 = Hash(bytes) };
        }

        public IReadOnlyList<EmittedFile> EmitMany(IEnumerable<WrapperFile> inputs)
        {
            if (inputs == null) throw new ArgumentNullException(nameof(inputs));
            return inputs.Select(Emit).OrderBy(x => x.RelativePath, StringComparer.Ordinal).ToList();
        }

        private string Render(WrapperFile file)
        {
            var lines = new List<string>();
            if (options.IncludeOwnershipMarker) lines.Add(OwnershipMarker.D9);
            foreach (var comment in file.HeaderComments ?? new List<string>()) lines.Add("// " + comment);
            if (!string.IsNullOrWhiteSpace(options.GeneratedBy)) lines.Add("// Generated by " + options.GeneratedBy.Trim());
            if (lines.Count != 0) lines.Add(string.Empty);
            foreach (var name in file.Usings ?? new List<string>()) lines.Add("using " + name.Trim().TrimEnd(';') + ";");
            if ((file.Usings ?? new List<string>()).Count != 0) lines.Add(string.Empty);
            if (!string.IsNullOrWhiteSpace(file.Namespace))
            {
                lines.Add("namespace " + file.Namespace.Trim());
                lines.Add("{");
                foreach (var type in file.Types) RenderType(lines, type, 1);
                lines.Add("}");
            }
            else foreach (var type in file.Types) RenderType(lines, type, 0);
            return string.Join("\r\n", lines).TrimEnd('\r', '\n') + "\r\n";
        }

        private static void RenderType(List<string> lines, WrapperType type, int level)
        {
            AddDocumentation(lines, type.Documentation, level);
            foreach (var attribute in type.Attributes ?? new List<string>()) Add(lines, level, attribute);
            var modifiers = string.Join(" ", new[] { type.Accessibility, type.Abstract ? "abstract" : null, type.Sealed ? "sealed" : null, type.Partial ? "partial" : null }.Where(x => !string.IsNullOrEmpty(x)));
            var declaration = modifiers + " " + type.Kind + " " + type.Name + (type.TypeParameters ?? string.Empty);
            if (type.Kind == "delegate") { Add(lines, level, modifiers + " delegate " + type.DelegateReturnType + " " + type.Name + (type.TypeParameters ?? string.Empty) + "(" + string.Join(", ", type.DelegateParameters.Select(RenderParameter)) + ");"); return; }
            Add(lines, level, declaration + "");
            Add(lines, level, "{");
            foreach (var member in type.Members ?? new List<WrapperMember>()) RenderMember(lines, member, level + 1, type.Kind == "interface");
            Add(lines, level, "}");
        }

        private static void RenderMember(List<string> lines, WrapperMember member, int level, bool inInterface)
        {
            AddDocumentation(lines, member.Documentation, level);
            foreach (var attribute in member.Attributes ?? new List<string>()) Add(lines, level, attribute);
            if (!string.IsNullOrWhiteSpace(member.Declaration)) { AddMultiline(lines, level, member.Declaration); return; }
            if (member.Kind == "enum-value") { Add(lines, level, member.Name + (string.IsNullOrWhiteSpace(member.Body) ? "," : " = " + member.Body + ",")); return; }
            var parameters = string.Join(", ", (member.Parameters ?? new List<WrapperParameter>()).Select(RenderParameter));
            var kind = member.Kind.ToLowerInvariant();
            var modifiers = inInterface ? string.Empty : string.Join(" ", new[] { member.Accessibility, member.Static ? "static" : null, member.Override ? "override" : null, member.Virtual ? "virtual" : null, member.Abstract ? "abstract" : null, member.ReadOnly ? "readonly" : null }.Where(x => !string.IsNullOrEmpty(x)));
            string signature;
            if (kind == "constructor" || kind == "ctor") signature = modifiers + " " + member.Name + "(" + parameters + ")";
            else if (kind == "event") signature = modifiers + " event " + member.Type + " " + member.Name;
            else if (kind == "field") signature = modifiers + " " + member.Type + " " + member.Name;
            else if (kind == "property" || kind == "indexer") signature = modifiers + " " + member.Type + " " + (kind == "indexer" ? "this[" + parameters + "]" : member.Name);
            else signature = modifiers + " " + member.Type + " " + member.Name + "(" + parameters + ")";
            if (!string.IsNullOrWhiteSpace(member.ExpressionBody)) signature += " => " + member.ExpressionBody.Trim() + ";";
            else if (inInterface && (kind == "property" || kind == "indexer")) signature += " { get; set; }";
            else if (inInterface || member.Abstract) signature += ";";
            else if (!string.IsNullOrWhiteSpace(member.Body)) signature += "\n" + member.Body.Trim();
            else if (kind == "property" || kind == "indexer") signature += " { get; set; }";
            else if (kind == "field") signature += ";";
            else signature += " { }";
            AddMultiline(lines, level, signature);
        }

        private static string RenderParameter(WrapperParameter parameter)
        {
            var modifier = parameter.Out ? "out " : parameter.Ref ? "ref " : parameter.In ? "in " : string.Empty;
            var value = string.IsNullOrWhiteSpace(parameter.DefaultValue) ? string.Empty : " = " + parameter.DefaultValue.Trim();
            return modifier + parameter.Type + " " + parameter.Name + value;
        }

        private static void AddDocumentation(List<string> lines, WrapperDocumentation documentation, int level)
        {
            if (documentation == null) return;
            AddXml(lines, level, "summary", documentation.Summary);
            foreach (var pair in documentation.TypeParameters.OrderBy(x => x.Key, StringComparer.Ordinal)) AddXml(lines, level, "typeparam name=\"" + Escape(pair.Key) + "\"", pair.Value);
            foreach (var pair in documentation.Parameters.OrderBy(x => x.Key, StringComparer.Ordinal)) AddXml(lines, level, "param name=\"" + Escape(pair.Key) + "\"", pair.Value);
            AddXml(lines, level, "returns", documentation.Returns);
            AddXml(lines, level, "value", documentation.Value);
            AddXml(lines, level, "remarks", documentation.Remarks);
            foreach (var exception in documentation.Exceptions.OrderBy(x => x, StringComparer.Ordinal)) AddXml(lines, level, "exception cref=\"" + Escape(exception) + "\"", exception);
            foreach (var example in documentation.Examples) AddXml(lines, level, "example", example);
        }

        private static void AddXml(List<string> lines, int level, string tag, string value)
        {
            if (string.IsNullOrWhiteSpace(value)) return;
            var escaped = Escape(value);
            var parts = escaped.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
            Add(lines, level, "/// <" + tag + ">");
            foreach (var part in parts) Add(lines, level, "/// " + part);
            Add(lines, level, "/// </" + tag.Split(' ')[0] + ">");
        }

        private static string Escape(string value) { return SecurityElement.Escape(value ?? string.Empty) ?? string.Empty; }
        private static void Add(List<string> lines, int level, string value) { lines.Add(new string(' ', level * 4) + value.TrimEnd()); }
        private static void AddMultiline(List<string> lines, int level, string value) { foreach (var line in value.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n')) Add(lines, level, line); }
        private static string Hash(byte[] bytes) { using (var sha = SHA256.Create()) return string.Concat(sha.ComputeHash(bytes).Select(x => x.ToString("x2"))); }
    }
}
