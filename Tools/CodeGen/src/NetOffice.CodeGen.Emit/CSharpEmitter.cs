        private static void RenderMember(List<string> lines, WrapperMember member, int level, bool inInterface, bool containingStatic, WrapperModuleRuntime moduleRuntime)
        {
            var kind = member.Kind.ToLowerInvariant();
            if (kind == "event" && member.UseCustomEventAccessors)
                Add(lines, level, "private event " + member.Type + " " + member.EventBackingField + ";");
            AddDocumentation(lines, member.Documentation, level);
            foreach (var attribute in member.Attributes ?? new List<string>()) Add(lines, level, NormalizeAttribute(attribute));
            var declarationFragment = IsDeclarationFragment(member);
            if (!string.IsNullOrWhiteSpace(member.Declaration) && !declarationFragment)
            {
                var rawDeclaration = member.Declaration.Trim();
                if (!rawDeclaration.EndsWith(";", StringComparison.Ordinal) && !rawDeclaration.EndsWith("}", StringComparison.Ordinal)) throw new InvalidOperationException("A complete member declaration must end in ';' or '}'.");
                AddMultiline(lines, level, rawDeclaration);
                return;
            }
            var parameters = string.Join(", ", (member.Parameters ?? new List<WrapperParameter>()).Select(parameter => RenderParameter(parameter, kind != "indexer", inInterface || member.PreserveParameterAttributes)));
            var explicitInterface = string.IsNullOrWhiteSpace(member.ExplicitInterface) ? null : member.ExplicitInterface.Trim() + ".";
            var accessibility = explicitInterface == null ? member.Accessibility : null;
            var modifiers = inInterface ? string.Empty : JoinTokens(accessibility, (containingStatic || member.Static) && !member.Const && kind != "constant" ? "static" : null, member.New ? "new" : null, member.Override ? "override" : null, member.Virtual ? "virtual" : null, member.Abstract ? "abstract" : null, member.Const || kind == "constant" ? "const" : null, member.ReadOnly ? "readonly" : null);
            string signature;
            if (declarationFragment && (kind == "method" || kind == "constructor" || kind == "ctor"))
                signature = JoinTokens(modifiers, kind == "constructor" || kind == "ctor" ? null : member.Type, NormalizeDeclarationFragment(member.Declaration));
            else if (kind == "constructor" || kind == "ctor") signature = JoinTokens(modifiers, member.Name) + "(" + parameters + ")";
            else if (kind == "event") signature = JoinTokens(modifiers, "event", member.Type, explicitInterface + member.Name);
            else if (kind == "field" || kind == "constant") signature = JoinTokens(modifiers, member.Type, member.Name);
            else if (kind == "property" || kind == "indexer")
            {
                var propertyName = kind == "indexer" ? explicitInterface + "this[" + (declarationFragment ? DeclarationArguments(member.Declaration) : parameters) + "]" : explicitInterface + member.Name;
                signature = JoinTokens(modifiers, member.Type, propertyName);
            }
            else signature = JoinTokens(modifiers, member.Type, explicitInterface + member.Name + (member.TypeParameters ?? string.Empty)) + "(" + parameters + ")";
            if ((kind == "constructor" || kind == "ctor") && !string.IsNullOrWhiteSpace(member.Initializer)) signature += " : " + member.Initializer.Trim().TrimStart(':').Trim();
            if (!string.IsNullOrWhiteSpace(member.ExpressionBody)) { Add(lines, level, signature + " => " + member.ExpressionBody.Trim() + ";"); return; }
            if (kind == "field" || kind == "constant")
            {
                Add(lines, level, signature + (string.IsNullOrWhiteSpace(member.Value) ? string.Empty : " = " + member.Value.Trim()) + ";");
                return;
            }
            if (kind == "property" || kind == "indexer" || (kind == "event" && (member.Accessors.Count != 0 || member.UseCustomEventAccessors)))
            {
                Add(lines, level, signature);
                Add(lines, level, "{");
                if (member.UseCustomEventAccessors)
                {
                    Add(lines, level + 1, "add");
                    Add(lines, level + 1, "{");
                    Add(lines, level + 2, "CreateEventBridge();");
                    Add(lines, level + 2, member.EventBackingField + " += value;");
                    Add(lines, level + 1, "}");
                    Add(lines, level + 1, "remove");
                    Add(lines, level + 1, "{");
                    Add(lines, level + 2, member.EventBackingField + " -= value;");
                    Add(lines, level + 1, "}");
                }
                else if (member.Accessors != null && member.Accessors.Count != 0)
                    foreach (var accessor in member.Accessors) RenderAccessor(lines, accessor, level + 1, inInterface || member.Abstract, moduleRuntime);
                else if (member.Invocation != null)
                    RenderAccessor(lines, new WrapperAccessor { Kind = "get", Invocation = member.Invocation }, level + 1, inInterface || member.Abstract, moduleRuntime);
                else
                {
                    Add(lines, level + 1, "get;");
                    Add(lines, level + 1, "set;");
                }
                Add(lines, level, "}");
                return;
            }
            if (inInterface || member.Abstract) { Add(lines, level, signature + ";"); return; }
            if (kind == "event") { Add(lines, level, signature + ";"); return; }
            var body = member.Invocation == null ? member.Body : InvocationBodyRenderer.Render(member.Invocation, moduleRuntime);
            Add(lines, level, signature);
            foreach (var constraint in member.Constraints ?? new List<string>()) Add(lines, level + 1, NormalizeConstraint(constraint));
            AddBody(lines, level, body ?? string.Empty);
        }

        private static void RenderAccessor(List<string> lines, WrapperAccessor accessor, int level, bool declarationOnly, WrapperModuleRuntime moduleRuntime)
        {
            foreach (var attribute in accessor.Attributes ?? new List<string>()) Add(lines, level, NormalizeAttribute(attribute));
            AddDocumentation(lines, accessor.Documentation, level);
            var prefix = JoinTokens(accessor.Accessibility, accessor.Kind);
            if (!string.IsNullOrWhiteSpace(accessor.ExpressionBody)) { Add(lines, level, prefix + " => " + accessor.ExpressionBody.Trim() + ";"); return; }
            if (declarationOnly) { Add(lines, level, prefix + ";"); return; }
            var body = accessor.Invocation == null ? accessor.Body : InvocationBodyRenderer.Render(accessor.Invocation, moduleRuntime);
            if (string.IsNullOrWhiteSpace(body)) { Add(lines, level, prefix + " { }"); return; }
            Add(lines, level, prefix);
            AddBody(lines, level, body);
        }

        private static void AddBody(List<string> lines, int level, string body)
        {
            var normalized = body.Trim();
            if (normalized.StartsWith("{", StringComparison.Ordinal)) AddMultiline(lines, level, normalized);
            else
            {
                Add(lines, level, "{");
                AddMultiline(lines, level + 1, normalized);
                Add(lines, level, "}");
            }
        }

        private static string RenderParameter(WrapperParameter parameter, bool allowByRef = true, bool includeAttributes = true)
        {
            if (parameter == null) throw new InvalidOperationException("A wrapper parameter cannot be null.");
            var attributes = !includeAttributes || parameter.Attributes == null || parameter.Attributes.Count == 0 ? string.Empty : string.Join(" ", parameter.Attributes.Select(NormalizeAttribute)) + " ";
            var modifier = parameter.Out && allowByRef ? "out " : parameter.Ref && allowByRef ? "ref " : parameter.In ? "in " : parameter.Params ? "params " : string.Empty;
            var value = string.IsNullOrWhiteSpace(parameter.DefaultValue) || parameter.Ref || parameter.Out ? string.Empty : " = " + parameter.DefaultValue.Trim();
            return attributes + modifier + parameter.Type + " " + parameter.Name + value;
        }

        private static void AddDocumentation(List<string> lines, WrapperDocumentation documentation, int level)
        {
            if (documentation == null) return;
            if (!string.IsNullOrWhiteSpace(documentation.RawXml))
            {
                foreach (var part in documentation.RawXml.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n'))
                    Add(lines, level, "/// " + part);
                return;
            }
            AddXml(lines, level, "summary", documentation.Summary);
            foreach (var pair in documentation.TypeParameters.OrderBy(x => x.Key, StringComparer.Ordinal)) AddXml(lines, level, "typeparam name=\"" + Escape(pair.Key) + "\"", pair.Value);
            foreach (var pair in documentation.Parameters.OrderBy(x => x.Key, StringComparer.Ordinal)) AddXml(lines, level, "param name=\"" + Escape(pair.Key) + "\"", pair.Value);
            AddXml(lines, level, "returns", documentation.Returns);
            AddXml(lines, level, "value", documentation.Value);
            AddXml(lines, level, "remarks", documentation.Remarks);
            foreach (var exception in documentation.Exceptions.OrderBy(x => x, StringComparer.Ordinal)) AddXml(lines, level, "exception cref=\"" + Escape(exception) + "\"", exception);
            foreach (var example in documentation.Examples) AddXml(lines, level, "example", example);
        }

        private static void AddXml(List<string> lines, int level, string tag, string value)
        {
            if (string.IsNullOrWhiteSpace(value)) return;
            var escaped = Escape(value);
            var parts = escaped.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
            var closeTag = tag.Split(' ')[0];
            Add(lines, level, "/// <" + tag + ">");
            foreach (var part in parts) Add(lines, level, "/// " + part);
            Add(lines, level, "/// </" + closeTag + ">");
        }

        private static string JoinTokens(params string[] values)
        {
            return string.Join(" ", values.Where(x => !string.IsNullOrWhiteSpace(x)).Select(x => x.Trim()));
        }
        private static bool IsDeclarationFragment(WrapperMember member)
        {
            if (string.IsNullOrWhiteSpace(member.Declaration) || string.IsNullOrWhiteSpace(member.Name)) return false;
            var kind = (member.Kind ?? string.Empty).Trim().ToLowerInvariant();
            if (kind != "method" && kind != "constructor" && kind != "ctor" && kind != "property" && kind != "indexer" && kind != "field" && kind != "event") return false;
            var text = member.Declaration.Trim();
            var open = text.IndexOf('(');
            if (open <= 0) return false;
            var prefix = text.Substring(0, open).Trim();
            return string.Equals(prefix, member.Name, StringComparison.Ordinal) || prefix.StartsWith(member.Name + "<", StringComparison.Ordinal);
        }

        private static string NormalizeDeclarationFragment(string declaration)
        {
            var text = declaration.Trim();
            var open = text.IndexOf('(');
            var close = text.LastIndexOf(')');
            if (open < 0 || close <= open) return text;
            return text.Substring(0, open).Trim() + "(" + NormalizeParameterList(text.Substring(open + 1, close - open - 1)) + ")";
        }

        private static string DeclarationArguments(string declaration)
        {
            var text = NormalizeDeclarationFragment(declaration);
            var open = text.IndexOf('(');
            var close = text.LastIndexOf(')');
            return open >= 0 && close > open ? text.Substring(open + 1, close - open - 1).Trim() : string.Empty;
        }

        private static string NormalizeParameterList(string value)
        {
            var result = (value ?? string.Empty).Trim();
            while (IsFullyParenthesized(result)) result = result.Substring(1, result.Length - 2).Trim();
            return result;
        }

        private static bool IsFullyParenthesized(string value)
        {
            if (value.Length < 2 || value[0] != '(' || value[value.Length - 1] != ')') return false;
            var depth = 0;
            for (var i = 0; i < value.Length; i++)
            {
                if (value[i] == '(') depth++;
                else if (value[i] == ')' && --depth == 0 && i != value.Length - 1) return false;
                if (depth < 0) return false;
            }
            return depth == 0;
        }

        private static string NormalizeConstraint(string value)
        {
            var text = (value ?? string.Empty).Trim();
            return text.StartsWith("where ", StringComparison.Ordinal) ? text : "where " + text;
        }

        private static string NormalizeAttribute(string value)
        {
            var text = (value ?? string.Empty).Trim();
            if (text.Length == 0) return text;
            return text.StartsWith("[", StringComparison.Ordinal) && text.EndsWith("]", StringComparison.Ordinal) ? text : "[" + text + "]";
        }

        private static string Escape(string value) { return SecurityElement.Escape(value ?? string.Empty) ?? string.Empty; }
        private static void Add(List<string> lines, int level, string value) { lines.Add(new string(' ', level * 4) + value.TrimEnd()); }
        private static void AddMultiline(List<string> lines, int level, string value) { foreach (var line in value.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n')) Add(lines, level, line); }
    }
