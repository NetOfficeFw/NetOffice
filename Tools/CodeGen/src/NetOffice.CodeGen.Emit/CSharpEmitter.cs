    public static class OwnershipMarker
    {
        public const string D9 = "// NetOffice.CodeGen ownership: D9";
    }

    public sealed class EmitterOptions
    {
        public string ProductName { get; set; }
        public string GeneratedBy { get; set; }
        public bool IncludeOwnershipMarker { get; set; } = true;
        public ISourceValidator Validator { get; set; } = new BasicSourceValidator();
    }

    public sealed class EmittedFile
    {
        private static readonly Encoding StrictUtf8 = new UTF8Encoding(false, true);
        public string RelativePath { get; internal set; }
        public byte[] Bytes { get; internal set; }
        public string Sha256 { get; internal set; }
        /// <summary>Restores external bytes and independently validates all emitted-source and C# 7.3 invariants.</summary>
        public static EmittedFile FromBytes(string relativePath, byte[] bytes, string expectedSha256)
        {
            return RestoreCore(relativePath, bytes, expectedSha256);
        }


        private static EmittedFile RestoreCore(string relativePath, byte[] bytes, string expectedSha256)
        {
            if (string.IsNullOrWhiteSpace(relativePath)) throw new ArgumentException("An emitted source path is required.", nameof(relativePath));
            var normalizedPath = WrapperFile.CanonicalPath(relativePath);
            if (System.IO.Path.IsPathRooted(relativePath) || normalizedPath.Split('/').Any(segment => segment == ".."))
                throw new ArgumentException("RelativePath must not escape the output root.", nameof(relativePath));
            if (bytes == null) throw new ArgumentNullException(nameof(bytes));
            if (bytes.Length < 3 || bytes[0] != 0xEF || bytes[1] != 0xBB || bytes[2] != 0xBF)
                throw new InvalidOperationException("Emitted source must use UTF-8 with BOM.");
            var expected = (expectedSha256 ?? string.Empty).Trim();
            if (expected.Length != 64 || !expected.All(Uri.IsHexDigit))
                throw new ArgumentException("Expected SHA-256 must contain 64 hexadecimal characters.", nameof(expectedSha256));
            var actual = ComputeSha256(bytes);
            if (!string.Equals(actual, expected, StringComparison.OrdinalIgnoreCase))
                throw new InvalidOperationException("Emitted source SHA-256 mismatch for " + normalizedPath + ".");
            try
            {
                new BasicSourceValidator().Validate(normalizedPath, StrictUtf8.GetString(bytes, 3, bytes.Length - 3));
            }
            catch (DecoderFallbackException exception)
            {
                throw new InvalidOperationException("Emitted source must contain valid UTF-8.", exception);
            }
            return new EmittedFile { RelativePath = normalizedPath, Bytes = bytes, Sha256 = actual };
        }

        internal static string ComputeSha256(byte[] bytes)
        {
            using (var sha = SHA256.Create()) return string.Concat(sha.ComputeHash(bytes).Select(value => value.ToString("x2")));
        }

        public long Length { get { return Bytes == null ? 0 : Bytes.LongLength; } }
        public string Text { get { return Bytes == null ? string.Empty : new UTF8Encoding(true).GetString(Bytes, 3, Bytes.Length - 3); } }
    }

    public interface ISourceValidator
    {
        void Validate(string relativePath, string source);
    }

    /// <summary>
    /// Validates emitted source invariants and reparses every file with Roslyn's
    /// C# 7.3 parser. Semantic binding is intentionally outside this emitter seam.
    /// </summary>
    public sealed class BasicSourceValidator : ISourceValidator
    {
        public void Validate(string relativePath, string source)
        {
            if (string.IsNullOrWhiteSpace(relativePath)) throw new InvalidOperationException("An emitted source path is required.");
            if (source == null || !source.EndsWith("\r\n", StringComparison.Ordinal)) throw new InvalidOperationException("Emitted source must end in CRLF.");
            if (source.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0) throw new InvalidOperationException("The D9 marker must not be an auto-generated marker.");
            var marker = OwnershipMarker.D9;
            var markerIndex = source.IndexOf(marker, StringComparison.Ordinal);
            if (markerIndex >= 0 && markerIndex != source.LastIndexOf(marker, StringComparison.Ordinal)) throw new InvalidOperationException("The ownership marker must occur at most once.");
            var braces = 0;
            var parentheses = 0;
            var brackets = 0;
            var inString = false;
            var verbatimString = false;
            var inChar = false;
            var inLineComment = false;
            var inBlockComment = false;
            for (var i = 0; i < source.Length; i++)
            {
                var ch = source[i];
                if (ch == '\n' && (i == 0 || source[i - 1] != '\r')) throw new InvalidOperationException("Emitted source must use CRLF.");
                if (inLineComment) { if (ch == '\n') inLineComment = false; continue; }
                if (inBlockComment) { if (ch == '*' && i + 1 < source.Length && source[i + 1] == '/') { inBlockComment = false; i++; } continue; }
                if (inString)
                {
                    if (verbatimString) { if (ch == '"' && i + 1 < source.Length && source[i + 1] == '"') i++; else if (ch == '"') inString = false; }
                    else if (ch == '\\') i++;
                    else if (ch == '"') inString = false;
                    continue;
                }
                if (inChar) { if (ch == '\\') i++; else if (ch == '\'') inChar = false; continue; }
                if (ch == '/' && i + 1 < source.Length && source[i + 1] == '/') { inLineComment = true; i++; continue; }
                if (ch == '/' && i + 1 < source.Length && source[i + 1] == '*') { inBlockComment = true; i++; continue; }
                if (ch == '@' && i + 1 < source.Length && source[i + 1] == '"') { inString = true; verbatimString = true; i++; continue; }
                if (ch == '"') { inString = true; verbatimString = false; continue; }
                if (ch == '\'') { inChar = true; continue; }
                if (ch == '{') braces++;
                else if (ch == '}' && --braces < 0) throw new InvalidOperationException("Unbalanced braces in " + relativePath + ".");
                else if (ch == '(') parentheses++;
                else if (ch == ')' && --parentheses < 0) throw new InvalidOperationException("Unbalanced parentheses in " + relativePath + ".");
                else if (ch == '[') brackets++;
                else if (ch == ']' && --brackets < 0) throw new InvalidOperationException("Unbalanced brackets in " + relativePath + ".");
            }
            if (braces != 0 || parentheses != 0 || brackets != 0 || inString || inChar || inBlockComment) throw new InvalidOperationException("Unbalanced C# delimiters in " + relativePath + ".");
            var tree = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.CSharp7_3, DocumentationMode.Parse), relativePath, new UTF8Encoding(false));
            var diagnostics = tree.GetDiagnostics().Where(x => x.Severity == DiagnosticSeverity.Error).ToList();
            if (diagnostics.Count != 0) throw new InvalidOperationException("C# 7.3 parse failed for " + relativePath + ": " + string.Join(" | ", diagnostics.Select(diagnostic => FormatParseDiagnostic(diagnostic, source))));
        }
        private static string FormatParseDiagnostic(Diagnostic diagnostic, string source)
        {
            var start = diagnostic.Location.GetLineSpan().StartLinePosition;
            var line = source.Split(new[] { "\r\n" }, StringSplitOptions.None).ElementAtOrDefault(start.Line) ?? string.Empty;
            return diagnostic.Id + " (" + (start.Line + 1) + "," + (start.Character + 1) + "): " + diagnostic.GetMessage() + " Source: " + line.Trim();
        }

    }

    public sealed class CSharpEmitter
    {
        private static readonly Encoding Utf8Bom = new UTF8Encoding(true);
        private readonly EmitterOptions options;

        public CSharpEmitter(EmitterOptions options = null) { this.options = options ?? new EmitterOptions(); }

        public EmittedFile Emit(WrapperFile input)
        {
            if (input == null) throw new ArgumentNullException(nameof(input));
            var file = input.Canonicalize();
            var source = Render(file);
            if (options.Validator != null) options.Validator.Validate(file.RelativePath, source);
            var encoded = Utf8Bom.GetBytes(source);
            var preamble = Utf8Bom.GetPreamble();
            var bytes = new byte[preamble.Length + encoded.Length];
            Buffer.BlockCopy(preamble, 0, bytes, 0, preamble.Length);
            Buffer.BlockCopy(encoded, 0, bytes, preamble.Length, encoded.Length);
            return new EmittedFile { RelativePath = file.RelativePath, Bytes = bytes, Sha256 = EmittedFile.ComputeSha256(bytes) };
        }

        public IReadOnlyList<EmittedFile> EmitMany(IEnumerable<WrapperFile> inputs)
        {
            if (inputs == null) throw new ArgumentNullException(nameof(inputs));
            return inputs.Select(Emit).OrderBy(x => x.RelativePath, StringComparer.Ordinal).ToList();
        }

        private string Render(WrapperFile file)
        {
            var lines = new List<string>();
            if (options.IncludeOwnershipMarker) lines.Add(OwnershipMarker.D9);
            foreach (var comment in file.HeaderComments ?? new List<string>()) lines.Add("// " + comment);
            if (!string.IsNullOrWhiteSpace(options.GeneratedBy)) lines.Add("// Generated by " + options.GeneratedBy.Trim());
            if (lines.Count != 0) lines.Add(string.Empty);
            var usings = RequiredUsings(file);
            foreach (var name in usings) lines.Add("using " + name.Trim().TrimEnd(';') + ";");
            if (usings.Count != 0) lines.Add(string.Empty);
            var explicitTypeNames = new HashSet<string>(file.Types.Select(type => type.Name), StringComparer.Ordinal);
            if (!string.IsNullOrWhiteSpace(file.Namespace))
            {
                lines.Add("namespace " + file.Namespace.Trim());
                lines.Add("{");
                foreach (var type in file.Types) RenderType(lines, type, 1, explicitTypeNames);
                lines.Add("}");
            }
            else foreach (var type in file.Types) RenderType(lines, type, 0, explicitTypeNames);
            return string.Join("\r\n", lines).TrimEnd('\r', '\n') + "\r\n";
        }

        private static IList<string> RequiredUsings(WrapperFile file)
        {
            var result = new HashSet<string>(file.Usings ?? new List<string>(), StringComparer.Ordinal);
            var attributes = file.Types.SelectMany(type =>
                (type.Attributes ?? new List<string>())
                    .Concat(RuntimeAttributes(type))
                    .Concat(EventBindingAttributes(type))
                    .Concat(ProjectInfoAttributes(type))
                    .Concat((type.Members ?? new List<WrapperMember>()).SelectMany(member =>
                        (member.Attributes ?? new List<string>())
                            .Concat(EmittedParameterAttributes(type, member))
                            .Concat((member.Accessors ?? new List<WrapperAccessor>()).SelectMany(accessor => accessor.Attributes ?? new List<string>())))));
            var attributeText = string.Join("\n", attributes);
            if (ContainsAny(attributeText, "ComImport", "Guid(", "InterfaceType(", "TypeLibType(", "ComVisible(", "ClassInterface(", "MarshalAs(", "UnmanagedType.", "DispId(", "PreserveSig"))
                result.Add("System.Runtime.InteropServices");
            if (ContainsAny(attributeText, "MethodImpl(", "MethodImplOptions.", "MethodCodeType."))
                result.Add("System.Runtime.CompilerServices");
            if (file.Types.Any(IsComEventInterface))
                result.Add("System.Runtime.InteropServices.ComTypes");
            if (file.Types.Any(type => type.Runtime != null || type.EventBinding != null))
                result.Add("System.ComponentModel");
            if (file.Types.Any(type => type.EventBinding != null))
                result.Add("System");
            if (UsesNetRuntimeSystem(file))
                result.Add("NetRuntimeSystem = System");
            if (UsesByRefInvocation(file))
                result.Add("System.Reflection");
            if (file.Types.Any(type => type.ProjectInfo != null))
            {
                result.Add("System");
                result.Add("System.Reflection");
            }
            return result.OrderBy(value => value, StringComparer.Ordinal).ToList();
        }

        private static IEnumerable<string> RuntimeAttributes(WrapperType type)
        {
            if (type.Runtime == null) return Enumerable.Empty<string>();
            return (type.Runtime.InstanceTypeContract == null ? Enumerable.Empty<string>() : type.Runtime.InstanceTypeContract.Attributes)
                .Concat(type.Runtime.LateBindingApiWrapperTypeContract == null ? Enumerable.Empty<string>() : type.Runtime.LateBindingApiWrapperTypeContract.Attributes);
        }

        private static IEnumerable<string> EventBindingAttributes(WrapperType type)
        {
            return type.EventBinding == null || type.EventBinding.Contracts == null
                ? Enumerable.Empty<string>()
                : type.EventBinding.Contracts.All().SelectMany(contract => contract.Attributes ?? new List<string>());
        }

        private static IEnumerable<string> ProjectInfoAttributes(WrapperType type)
        {
            return type.ProjectInfo == null || type.ProjectInfo.Contracts == null
                ? Enumerable.Empty<string>()
                : type.ProjectInfo.Contracts.All().SelectMany(contract => contract.Attributes ?? new List<string>());
        }

        private static IEnumerable<string> EmittedParameterAttributes(WrapperType type, WrapperMember member)
        {
            return type.Kind == "interface" || member.PreserveParameterAttributes
                ? (member.Parameters ?? new List<WrapperParameter>()).SelectMany(parameter => parameter.Attributes ?? new List<string>())
                : Enumerable.Empty<string>();
        }

        private static bool ContainsAny(string value, params string[] tokens)
        {
            return tokens.Any(token => value.IndexOf(token, StringComparison.Ordinal) >= 0);
        }

        private static bool IsComEventInterface(WrapperType type)
        {
            return type.Kind == "interface" && (type.Attributes ?? new List<string>()).Any(attribute => attribute.IndexOf("InternalEntityKind.ComEventInterface", StringComparison.Ordinal) >= 0);
        }

        private static bool UsesNetRuntimeSystem(WrapperFile file)
        {
            return file.Types.Any(type =>
                type.Runtime != null || type.EventBinding != null ||
                (type.Members ?? new List<WrapperMember>()).Any(member =>
                    UsesNetRuntimeSystem(member.Invocation) ||
                    (member.Accessors ?? new List<WrapperAccessor>()).Any(accessor => UsesNetRuntimeSystem(accessor.Invocation))));
        }

        private static bool UsesNetRuntimeSystem(WrapperInvocation invocation)
        {
            return invocation != null && invocation.Api == WrapperInvocationApi.Invoker &&
                (invocation.ReturnKind == WrapperReturnKind.Scalar || invocation.ReturnKind == WrapperReturnKind.Enum);
        }

        private static bool UsesByRefInvocation(WrapperFile file)
        {
            return file.Types.Any(type =>
                (type.Members ?? new List<WrapperMember>()).Any(member =>
                    UsesByRefInvocation(member.Invocation) ||
                    (member.Accessors ?? new List<WrapperAccessor>()).Any(accessor => UsesByRefInvocation(accessor.Invocation))));
        }

        private static bool UsesByRefInvocation(WrapperInvocation invocation)
        {
            return invocation != null && (invocation.Arguments ?? new List<WrapperInvocationArgument>()).Any(argument => argument.ByRef);
        }

        private static void RenderType(List<string> lines, WrapperType type, int level, ISet<string> explicitTypeNames)
        {
            AddDocumentation(lines, type.Documentation, level);
            foreach (var attribute in type.Attributes ?? new List<string>()) Add(lines, level, NormalizeAttribute(attribute));
            var sourceKind = type.Kind == "module" || type.Kind == "constants" ? "class" : type.Kind;
            var isStatic = type.Static || type.Kind == "module" || type.Kind == "constants";
            var modifiers = JoinTokens(string.Equals(type.Accessibility, "private", StringComparison.Ordinal) ? null : type.Accessibility, isStatic ? "static" : null, type.Abstract ? "abstract" : null, type.Sealed ? "sealed" : null, type.Partial ? "partial" : null);
            var typeParameters = type.TypeParameters ?? string.Empty;
            var declaration = JoinTokens(modifiers, sourceKind, type.Name + typeParameters);
            if (type.BaseTypes != null && type.BaseTypes.Count != 0 && type.Kind != "delegate") declaration += " : " + string.Join(", ", type.BaseTypes);
            if (type.Kind == "delegate")
            {
                var delegateDeclaration = JoinTokens(modifiers, "delegate", type.DelegateReturnType, type.Name + typeParameters) + "(" + string.Join(", ", type.DelegateParameters.Select(parameter => RenderParameter(parameter))) + ")";
                if (type.Constraints == null || type.Constraints.Count == 0) Add(lines, level, delegateDeclaration + ";");
                else
                {
                    Add(lines, level, delegateDeclaration);
                    for (var index = 0; index < type.Constraints.Count; index++)
                        Add(lines, level + 1, NormalizeConstraint(type.Constraints[index]) + (index == type.Constraints.Count - 1 ? ";" : string.Empty));
                }
                return;
            }
            Add(lines, level, declaration);
            foreach (var constraint in type.Constraints ?? new List<string>()) Add(lines, level + 1, NormalizeConstraint(constraint));
            Add(lines, level, "{");
            if (type.Kind == "enum")
            {
                var values = type.Members ?? new List<WrapperMember>();
                for (var index = 0; index < values.Count; index++) RenderEnumValue(lines, values[index], level + 1, index != values.Count - 1);
            }
            else
            {
                if (type.ProjectInfo != null)
                    RenderProjectInfo(lines, type, level + 1);
                else
                {
                    if (type.EventBinding != null) RenderEventBindingFields(lines, type.EventBinding, level + 1);
                    if (type.Runtime != null) RenderRuntime(lines, type, level + 1);
                    if (type.ModuleRuntime != null) RenderModuleRuntime(lines, type, level + 1);
                    foreach (var member in (type.Members ?? new List<WrapperMember>()).Where(member => !member.EventSinkOnly)) RenderMember(lines, member, level + 1, type.Kind == "interface", isStatic, type.ModuleRuntime);
                    if (type.EventBinding != null) RenderEventBindingMembers(lines, type.EventBinding, level + 1);
                }
            }
            Add(lines, level, "}");
            if (IsComEventInterface(type) && !explicitTypeNames.Contains(type.Name + "_SinkHelper")) RenderEventSink(lines, type, level);
        }

        private static void RenderEventSink(List<string> lines, WrapperType eventInterface, int level)
        {
            var sinkName = eventInterface.Name + "_SinkHelper";
            var id = EventInterfaceId(eventInterface);
            Add(lines, level, "[InternalEntity(InternalEntityKind.SinkHelper)]");
            Add(lines, level, "[ComVisible(true), ClassInterface(ClassInterfaceType.None), TypeLibType(TypeLibTypeFlags.FHidden)]");
            Add(lines, level, "public class " + sinkName + " : SinkHelper, " + eventInterface.Name);
            Add(lines, level, "{");
            Add(lines, level + 1, "public static readonly string Id = " + CSharpString(id) + ";");
            Add(lines, level + 1, "public " + sinkName + "(ICOMObject eventClass, IConnectionPoint connectPoint) : base(eventClass)");
            Add(lines, level + 1, "{");
            Add(lines, level + 2, "SetupEventBinding(connectPoint);");
            Add(lines, level + 1, "}");
            foreach (var member in eventInterface.Members.Where(member => member.Kind == "method"))
                RenderEventSinkMethod(lines, member, level + 1);
            Add(lines, level, "}");
        }

        private static void RenderEventSinkMethod(List<string> lines, WrapperMember member, int level)
        {
            var parameters = member.Parameters ?? new List<WrapperParameter>();
            var signature = "public " + member.Type + " " + member.Name + (member.TypeParameters ?? string.Empty) + "(" + string.Join(", ", parameters.Select(parameter => RenderParameter(parameter))) + ")";
            Add(lines, level, signature);
            Add(lines, level, "{");
            foreach (var parameter in parameters.Where(parameter => parameter.Out))
                Add(lines, level + 1, parameter.Name + " = default(" + parameter.Type + ");");
            var validationKey = string.IsNullOrWhiteSpace(member.EventValidationKey) ? member.Name : member.EventValidationKey;
            Add(lines, level + 1, "if (!Validate(" + CSharpString(validationKey) + "))");
            Add(lines, level + 1, "{");
            string validationRelease = null;
            if (member.EventValidationReleaseMode == WrapperEventValidationReleaseMode.Explicit)
                validationRelease = "Invoker.ReleaseParamsArray(" + string.Join(", ", member.EventValidationReleaseArguments) + ");";
            else if (member.EventValidationReleaseMode == WrapperEventValidationReleaseMode.Default && parameters.Count != 0)
                validationRelease = "Invoker.ReleaseParamsArray(" + string.Join(", ", parameters.Select(parameter => parameter.Name)) + ");";
            if (validationRelease != null)
                Add(lines, level + 2, validationRelease + (member.EventValidationInlineReturn ? " return;" : string.Empty));
            if (!member.EventValidationInlineReturn)
                Add(lines, level + 2, member.Type == "void" ? "return;" : "return default(" + member.Type + ");");
            Add(lines, level + 1, "}");
            var projectedArguments = new List<string>(parameters.Count);
            foreach (var parameter in parameters)
            {
                var expression = RenderEventArgumentConversion(parameter);
                if (expression == parameter.Name)
                {
                    projectedArguments.Add(expression);
                    continue;
                }
                var localName = string.IsNullOrWhiteSpace(parameter.EventConversion.LocalName) ? "new" + parameter.Name : parameter.EventConversion.LocalName;
                Add(lines, level + 1, parameter.EventConversion.ManagedType + " " + localName + " = " + expression + ";");
                projectedArguments.Add(localName);
            }
            Add(lines, level + 1, "object[] paramsArray = new object[" + parameters.Count + "];");
            for (var index = 0; index < projectedArguments.Count; index++)
                Add(lines, level + 1, "paramsArray[" + index + "] = " + projectedArguments[index] + ";");
            Add(lines, level + 1, "EventBinding.RaiseCustomEvent(" + CSharpString(member.Name) + ", ref paramsArray);");
            for (var index = 0; index < parameters.Count; index++)
            {
                var parameter = parameters[index];
                if (parameter.Ref || parameter.Out)
                    Add(lines, level + 1, parameter.Name + " = " + RenderEventWriteBack(parameter, "paramsArray[" + index + "]") + ";");
            }
            if (member.Type != "void") Add(lines, level + 1, "return default(" + member.Type + ");");
            Add(lines, level, "}");
        }

        private static string RenderEventArgumentConversion(WrapperParameter parameter)
        {
            var conversion = parameter.EventConversion;
            if (conversion == null || conversion.Kind == WrapperEventArgumentKind.Raw) return parameter.Name;
            var sourceArgument = string.IsNullOrWhiteSpace(conversion.SourceArgument) ? parameter.Name : conversion.SourceArgument;
            if (!string.IsNullOrWhiteSpace(conversion.ConversionExpression))
                return conversion.ConversionExpression.Replace("{0}", sourceArgument);
            switch (conversion.Kind)
            {
                case WrapperEventArgumentKind.Scalar:
                    return "To" + ScalarConversionName(conversion.ManagedType) + "(" + sourceArgument + ")";
                case WrapperEventArgumentKind.Enum:
                    return "(" + conversion.ManagedType + ")" + sourceArgument;
                case WrapperEventArgumentKind.KnownReference:
                    return "Factory.CreateKnownObjectFromComProxy<" + conversion.ManagedType + ">(EventClass, " + sourceArgument + ", " + conversion.WrapperTypeExpression + ")";
                case WrapperEventArgumentKind.EventReference:
                    return "Factory.CreateEventArgumentObjectFromComProxy(EventClass, " + sourceArgument + ") as " + conversion.ManagedType;
                default:
                    throw new InvalidOperationException("Unsupported event argument conversion: " + conversion.Kind);
            }
        }

        private static string RenderEventWriteBack(WrapperParameter parameter, string expression)
        {
            var conversion = parameter.EventConversion;
            if (conversion == null || conversion.Kind == WrapperEventArgumentKind.Raw) return "(" + parameter.Type + ")" + expression;
            if (!string.IsNullOrWhiteSpace(conversion.WriteBackExpression))
                return conversion.WriteBackExpression.Replace("{0}", expression);
            switch (conversion.Kind)
            {
                case WrapperEventArgumentKind.Scalar:
                    return "To" + ScalarConversionName(conversion.ManagedType) + "(" + expression + ")";
                case WrapperEventArgumentKind.Enum:
                    return "(" + conversion.ManagedType + ")" + expression;
                default:
                    return expression;
            }
        }

        private static string ScalarConversionName(string type)
        {
            switch ((type ?? string.Empty).Trim())
            {
                case "short": case "Int16": case "System.Int16": case "global::System.Int16": return "Int16";
                case "int": case "Int32": case "System.Int32": case "global::System.Int32": return "Int32";
                case "float": case "Single": case "System.Single": case "global::System.Single": return "Single";
                case "double": case "Double": case "System.Double": case "global::System.Double": return "Double";
                case "string": case "String": case "System.String": case "global::System.String": return "String";
                case "bool": case "Boolean": case "System.Boolean": case "global::System.Boolean": return "Bool";
                default: throw new InvalidOperationException("A scalar event conversion expression is required for " + type + ".");
            }
        }

        private static string EventInterfaceId(WrapperType type)
        {
            foreach (var attribute in type.Attributes ?? new List<string>())
            {
                var guid = attribute.IndexOf("Guid(", StringComparison.Ordinal);
                if (guid < 0) continue;
                var firstQuote = attribute.IndexOf('"', guid);
                var secondQuote = firstQuote < 0 ? -1 : attribute.IndexOf('"', firstQuote + 1);
                if (firstQuote >= 0 && secondQuote > firstQuote) return attribute.Substring(firstQuote + 1, secondQuote - firstQuote - 1);
            }
            return string.Empty;
        }

        private static string CSharpString(string value)
        {
            return "\"" + (value ?? string.Empty).Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
        }

        private static void RenderEnumValue(List<string> lines, WrapperMember member, int level, bool hasFollowing)
        {
            AddDocumentation(lines, member.Documentation, level);
            foreach (var attribute in member.Attributes ?? new List<string>()) Add(lines, level, NormalizeAttribute(attribute));
            Add(lines, level, member.Name + " = " + member.Value + (hasFollowing ? "," : string.Empty));
        }

        private static void RenderModuleRuntime(List<string> lines, WrapperType type, int level)
        {
            var runtime = type.ModuleRuntime;
            var memberNames = new HashSet<string>((type.Members ?? new List<WrapperMember>()).Select(member => member.Name), StringComparer.Ordinal);
            Add(lines, level, "private static " + runtime.InstanceType + " " + runtime.InstanceField + ";");
            if (!memberNames.Contains(runtime.InstanceProperty))
            {
                Add(lines, level, "internal static " + runtime.InstanceType + " " + runtime.InstanceProperty);
                Add(lines, level, "{");
                Add(lines, level + 1, "get { return " + runtime.InstanceField + "; }");
                Add(lines, level + 1, "set");
                Add(lines, level + 1, "{");
                Add(lines, level + 2, "if ((null == value) || (null == " + runtime.InstanceField + ")) " + runtime.InstanceField + " = value;");
                Add(lines, level + 1, "}");
                Add(lines, level, "}");
            }
            if (!memberNames.Contains(runtime.FactoryProperty))
            {
                Add(lines, level, "internal static " + runtime.CoreType + " " + runtime.FactoryProperty);
                Add(lines, level, "{");
                Add(lines, level + 1, "get");
                Add(lines, level + 1, "{");
                Add(lines, level + 2, "if(null != " + runtime.InstanceField + ")");
                Add(lines, level + 3, "return " + runtime.InstanceField + ".Factory;");
                Add(lines, level + 2, "else");
                Add(lines, level + 3, "return " + runtime.CoreType + ".Default;");
                Add(lines, level + 1, "}");
                Add(lines, level, "}");
